"use client";

import { useState } from "react";
import type { MotionPrep, PrepSide } from "@/lib/motionPrep";

/**
 * "Prep this motion" (DebateOwl's prep cards): both sides' strongest point
 * and one "If they say..." exchange. Collapsed by default and loaded only
 * when opened, so nobody pays for prep they did not ask for. The same prep
 * for everyone; a failure just says the debate works without it.
 */
export default function PrepCards({ topicId }: { topicId: string }) {
  const [state, setState] = useState<"idle" | "loading" | "ready" | "error">("idle");
  const [prep, setPrep] = useState<MotionPrep | null>(null);
  const [error, setError] = useState<string | null>(null);

  async function load() {
    if (state === "loading" || state === "ready") return;
    setState("loading");
    try {
      const res = await fetch(`/api/prep?topicId=${encodeURIComponent(topicId)}`);
      const data = await res.json();
      if (!res.ok || !data.prep) throw new Error(data.error || "Prep is not available right now.");
      setPrep(data.prep as MotionPrep);
      setState("ready");
    } catch (err) {
      setError(err instanceof Error ? err.message : "Prep is not available right now.");
      setState("error");
    }
  }

  return (
    <details
      className="surface-card p-4"
      data-testid="prep-cards"
      onToggle={(event) => {
        if ((event.currentTarget as HTMLDetailsElement).open) void load();
      }}
    >
      <summary className="cursor-pointer text-sm font-semibold">Prep this motion</summary>
      <p className="mt-1 text-xs text-ink3">
        The strongest point on each side and the reply to its likeliest objection. Generated by an AI from the motion alone,
        the same for everyone: a starting point, not a verdict.
      </p>
      {state === "loading" && (
        <p className="mt-3 text-sm text-ink3" role="status">
          Preparing…
        </p>
      )}
      {state === "error" && (
        <p className="mt-3 text-sm text-ink3" role="status">
          {error}
        </p>
      )}
      {state === "ready" && prep && (
        <div className="mt-3 grid gap-3 sm:grid-cols-2">
          <PrepSideCard label="For" side={prep.for} />
          <PrepSideCard label="Against" side={prep.against} />
        </div>
      )}
    </details>
  );
}

function PrepSideCard({ label, side }: { label: string; side: PrepSide }) {
  return (
    <section className="rounded-lg border border-[var(--rule)] bg-surface-2 p-3 text-sm" aria-label={`${label} prep`}>
      <p className="text-xs font-semibold uppercase tracking-[0.14em] text-ink3">{label}</p>
      <p className="mt-1">{side.strongest}</p>
      <p className="mt-2 text-ink2">
        <span className="font-medium">If they say:</span> &ldquo;{side.ifTheySay}&rdquo;
      </p>
      <p className="mt-1 text-ink2">
        <span className="font-medium">You can reply:</span> {side.reply}
      </p>
    </section>
  );
}
